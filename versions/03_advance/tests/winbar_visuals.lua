vim.opt.rtp:prepend(vim.fn.getcwd())
require('config.toggle_state').write('editor_winbar', true)
local bar=require('config.winbar');bar.setup()
local path=vim.fn.tempname()..'.lua';vim.fn.writefile({'one','two','three'},path)
vim.cmd.edit(path)
local buf=vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(buf,1,2,false,{'replacement','new'})
local add,del=require('config.buffer_changes').count(buf)
assert(add==2 and del==1, 'unsaved diff counts incorrect')
local rendered=bar.render()
assert(rendered:find('ConfigWinbarAddedActive',1,true) and rendered:find('ConfigWinbarRemovedActive',1,true))
assert(vim.api.nvim_eval_statusline(rendered,{winid=0,use_winbar=true}).str:find('+2 -1',1,true))
vim.cmd.write()
add,del=require('config.buffer_changes').count(buf);assert(add==0 and del==0)
vim.bo[buf].modified=true
assert(vim.api.nvim_eval_statusline(bar.render(),{winid=0,use_winbar=true}).str:find(' ●',1,true), 'modified flag without line changes must remain visible')
vim.api.nvim_buf_set_lines(buf,0,1,false,{})
add,del=require('config.buffer_changes').count(buf);assert(add==0 and del==1)
vim.api.nvim_set_hl(0,'Normal',{bg=0x121212,fg=0xeeeeee})
bar.apply_highlights()
assert(vim.api.nvim_get_hl(0,{name='ConfigWinbarActive'}).bg==0x121212)
assert(vim.api.nvim_get_hl(0,{name='ConfigWinbarInactive'}).bg~=0x121212)
vim.api.nvim_set_hl(0,'Normal',{fg=0xeeeeee})
bar.apply_highlights()
assert(vim.api.nvim_get_hl(0,{name='ConfigWinbarActive'}).bg==nil,'transparent Normal background not preserved')
local captured
package.loaded['config.picker']={action_picker=function(_,entries,opts) captured={entries,opts} end}
package.loaded['config.settings']=nil
local settings=require('config.settings')
settings.open()
assert(captured[1][1].label=='Lazy settings' and captured[1][#captured[1]].label=='Editor settings')
assert(captured[2].picker_opts.sorting_strategy=='descending')
settings.open('editor')
assert(captured[1][1].label=='< Back' and captured[1][#captured[1]].label:find('Window buffer bar',1,true))
print('PASS: simultaneous +/- counts, write baseline reset, active-background integration, transparency, descending settings priorities')
vim.cmd('qa!')
