vim.opt.rtp:prepend(vim.fn.getcwd())
require('config.toggle_state').write('editor_winbar',true)
local bar=require('config.winbar')
bar.setup()
require('config.keymaps')
local function file()
 local path=vim.fn.tempname()
 vim.fn.writefile({'first','second'},path)
 local buf=vim.fn.bufadd(path); vim.fn.bufload(buf);vim.bo[buf].buflisted=true
 return buf
end
local a,b,c=file(),file(),file()
local first=vim.api.nvim_get_current_win()
for _,buf in ipairs({a,b,c}) do vim.api.nvim_win_set_buf(first,buf) end
vim.cmd('vsplit')
local second=vim.api.nvim_get_current_win()
vim.api.nvim_set_current_win(first)
vim.api.nvim_win_set_cursor(first,{2,2})
vim.fn.maparg('<leader>bh','n',false,true).callback()
assert(vim.api.nvim_get_current_buf()==b)
vim.fn.maparg('<leader>b<Right>','n',false,true).callback()
assert(vim.api.nvim_get_current_buf()==c)
vim.api.nvim_win_set_cursor(first,{2,2})
local before=vim.fn.winsaveview()
vim.fn.maparg('<leader>bH','n',false,true).callback()
assert(vim.deep_equal(bar.items(first),{a,c,b}))
assert(vim.deep_equal(bar.items(second),{c}))
assert(vim.deep_equal(before,vim.fn.winsaveview()))
vim.fn.maparg('<leader>bL','n',false,true).callback()
assert(vim.deep_equal(bar.items(first),{a,b,c}))
assert(not bar.move_current(1))
bar.move_current(-1)
local expected=bar.snapshot(first)
local layout=require('config.sessions.layout')
assert(layout.restore(vim.json.decode(vim.json.encode(layout.snapshot()))))
assert(vim.deep_equal(bar.snapshot(vim.api.nvim_get_current_win()),expected))
require('config.editor_settings').cycle('winbar')
assert(not bar.move_current(-1))
print('PASS: bh/bl mappings, window isolation, cursor/view preservation, boundaries, session order, disabled behavior')
vim.cmd('qa!')
