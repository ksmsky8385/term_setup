vim.opt.rtp:prepend(vim.fn.getcwd())
require('config.toggle_state').write('editor_winbar',true)
local bar=require('config.winbar');bar.setup()
require('config.keymaps')
local float=require('config.floating')
local state=require('config.floating.state')
local function file()
 local path=vim.fn.tempname()..'.lua';vim.fn.writefile({'hello'},path)
 local b=vim.fn.bufadd(path);vim.fn.bufload(b);vim.bo[b].buflisted=true;return b
end
local a,b,c=file(),file(),file()
assert(float.open_buffer(a,{slot_id='1'}))
local w=vim.api.nvim_get_current_win()
assert(vim.wo[w].winbar~='','float has no winbar')
assert(vim.api.nvim_win_get_config(w).title==nil or #vim.api.nvim_win_get_config(w).title==0,'border title still shown')
assert(bar.render():find(' [1] ',1,true),'slot prefix missing')
float.open_buffer(b,{slot_id='1'})
assert(vim.deep_equal(bar.items(w),{a,b}),'reassignment lost history')
bar.cycle(-1);assert(vim.api.nvim_get_current_buf()==a)
bar.move_current(1);assert(vim.deep_equal(bar.items(w),{b,a}))
local ok,w2=float.split('vertical');assert(ok and w2)
float.set_window_buffer(w2,c)
assert(vim.deep_equal(bar.items(w2),{c}),'split inherited history')
assert(vim.deep_equal(bar.items(w),{b,a}),'split lost source history')
require('config.floating.window').hide_slot('1')
assert(bar.has_reference(a),'hidden float reference lost')
local main=vim.api.nvim_get_current_win()
vim.api.nvim_win_set_buf(main,a);bar.track(main)
assert(bar.close(main,a,true) and vim.api.nvim_buf_is_valid(a),'normal close deleted a hidden floating reference')
assert(state.assigned_slots_by_buffer()[a], 'hidden floating assignment missing from buffer list')
float.open_slot('1')
w=state.slots['1'].panes.A.win;w2=state.slots['1'].panes.B.win
assert(vim.deep_equal(bar.items(w),{b,a}),'reopen lost history order')
assert(vim.deep_equal(bar.items(w2),{c}))
local saved=state.current_slots()[1]
assert(#saved.panes[1].winbar==2,'session omitted hidden buffers')
require('config.floating.window').hide_slot('1')
state.slots={};saved.visible=true
assert(float.restore_group(saved))
w=state.slots['1'].panes.A.win;w2=state.slots['1'].panes.B.win
assert(vim.deep_equal(bar.items(w),{b,a}),'session restore lost history')
vim.api.nvim_set_current_win(w)
float.close_current(false)
assert(vim.api.nvim_win_is_valid(w) and vim.api.nvim_win_get_buf(w)==b,'q should cycle within pane')
assert(not vim.api.nvim_buf_is_valid(a),'last reference not deleted')
float.close_current(false)
assert(not vim.api.nvim_win_is_valid(w),'last entry did not close pane')
assert(vim.api.nvim_buf_is_valid(c),'other pane buffer deleted')
require('config.toggle_state').write('editor_winbar',false);bar.refresh()
assert(vim.wo[w2].winbar=='','toggle did not hide floating winbar')
assert(vim.api.nvim_win_get_config(w2).title and #vim.api.nvim_win_get_config(w2).title>0,'disabled winbar did not restore title')
print('PASS: floating histories, split isolation, cycle/reorder, hide/show, session roundtrip, q close and toggle')
vim.cmd('qa!')
