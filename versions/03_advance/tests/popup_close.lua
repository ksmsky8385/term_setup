vim.opt.rtp:prepend(vim.fn.getcwd())
require('config.keymaps')
local function popup() vim.api.nvim_exec_autocmds('MenuPopup',{pattern='n',group='ConfigPopupWindowClose'}) end
popup()
assert(vim.tbl_isempty(vim.fn.menu_info('PopUp.Close Window','n')))
local first=vim.api.nvim_get_current_win()
vim.cmd('vsplit')
local second=vim.api.nvim_get_current_win()
popup()
assert(not vim.tbl_isempty(vim.fn.menu_info('PopUp.Close Window','n')))
vim.cmd([[emenu PopUp.Close\ Window]])
assert(not vim.api.nvim_win_is_valid(second) and vim.api.nvim_win_is_valid(first))
popup()
assert(vim.tbl_isempty(vim.fn.menu_info('PopUp.Close Window','n')))
vim.cmd('WindowCloseFromPopup')
assert(vim.api.nvim_win_is_valid(first))
vim.cmd('vnew')
vim.bo.filetype='NvimTree'
popup()
assert(vim.tbl_isempty(vim.fn.menu_info('PopUp.Close Window','n')))
print('PASS: popup close appears for multiple editor windows, closes target, preserves last window and excludes tree')
vim.cmd('qa!')
