vim.opt.rtp:prepend(vim.fn.getcwd())
require('config.toggle_state').write('editor_winbar', true)
local bar=require('config.winbar');bar.setup()
require('config.keymaps')
local function file()
 local b=vim.api.nvim_create_buf(true,false)
 vim.api.nvim_buf_set_name(b,vim.fn.tempname()..'.txt')
 vim.api.nvim_win_set_buf(0,b)
 bar.track(vim.api.nvim_get_current_win())
 return b
end
local left=vim.api.nvim_get_current_win()
local a=file();local b=file()
vim.cmd('vnew');local right=vim.api.nvim_get_current_win()
bar.clear_window(right)
local c=file()
vim.api.nvim_set_current_win(left)
vim.fn.maparg('<leader>q','n',false,true).callback()
assert(vim.api.nvim_get_current_buf()==a,'must select own history')
assert(vim.api.nvim_buf_is_valid(c),'other window buffer was deleted')
vim.fn.maparg('<leader>q','n',false,true).callback()
assert(not vim.api.nvim_win_is_valid(left),'last entry must close split')
assert(vim.api.nvim_win_get_buf(right)==c)
vim.cmd('vnew');local extra=vim.api.nvim_get_current_win()
bar.clear_window(extra);vim.api.nvim_win_set_buf(extra,c);bar.track(extra)
vim.fn.maparg('<leader>Q','n',false,true).callback()
assert(not vim.api.nvim_win_is_valid(extra) and vim.api.nvim_buf_is_valid(c),'shared buffer must survive')
vim.cmd('vnew');local dirtywin=vim.api.nvim_get_current_win();bar.clear_window(dirtywin)
local dirty=file();vim.api.nvim_buf_set_lines(dirty,0,-1,false,{'unsaved'})
vim.fn.maparg('<leader>q','n',false,true).callback()
assert(vim.api.nvim_win_is_valid(dirtywin) and vim.api.nvim_buf_is_valid(dirty),'modified buffer must be protected')
vim.fn.maparg('<leader>Q','n',false,true).callback()
assert(not vim.api.nvim_win_is_valid(dirtywin) and not vim.api.nvim_buf_is_valid(dirty))
print('PASS: window-local replacement, last-entry split close, shared reference, q/Q protection')
vim.cmd('qa!')
