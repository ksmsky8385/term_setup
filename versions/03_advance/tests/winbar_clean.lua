vim.opt.rtp:prepend(vim.fn.getcwd())
vim.o.shell = '/bin/sh'
local settings = require('config.toggle_state')
settings.write('editor_winbar', true)
local bar = require('config.winbar')
bar.setup()
require('config.keymaps')
local source = vim.api.nvim_get_current_win()
local function file()
    local buf = vim.api.nvim_create_buf(true, false)
    vim.api.nvim_buf_set_name(buf, vim.fn.tempname() .. '.txt')
    vim.api.nvim_win_set_buf(source, buf)
    return buf
end
local removable = file()
local shared = file()
local dirty = file()
vim.api.nvim_buf_set_lines(dirty, 0, -1, false, {'unsaved'})
vim.cmd('terminal')
local term = vim.api.nvim_get_current_buf()
local job = vim.b[term].terminal_job_id
local pending = require('config.terminal').restore_buffer({cwd = vim.fn.getcwd()})
vim.api.nvim_win_set_buf(source, pending)
local current = file()
vim.cmd('vnew')
local other = vim.api.nvim_get_current_win()
bar.clear_window(other)
vim.api.nvim_win_set_buf(other, shared)
local other_history = bar.items(other)
vim.api.nvim_set_current_win(source)
local clean = vim.fn.maparg('<leader>bc', 'n', false, true).callback
assert(type(clean) == 'function')
clean()
assert(vim.deep_equal(bar.items(source), {dirty, term, pending, current}), 'wrong retained entries')
assert(not vim.api.nvim_buf_is_valid(removable), 'unreferenced buffer not closed')
assert(vim.api.nvim_buf_is_valid(shared), 'shared buffer deleted')
assert(vim.deep_equal(bar.items(other), other_history), 'other history changed')
assert(vim.api.nvim_get_current_win() == source and vim.api.nvim_get_current_buf() == current)
assert(vim.fn.jobwait({job}, 0)[1] == -1, 'terminal stopped')
assert(vim.b[pending].pending_terminal_restore, 'pending terminal changed')
clean()
assert(vim.deep_equal(bar.items(source), {dirty, term, pending, current}), 'repeat changed retained entries')
local additional = file()
vim.api.nvim_win_set_buf(source, current)
settings.write('editor_winbar', false)
clean()
assert(vim.api.nvim_buf_is_valid(additional), 'disabled winbar still cleaned')
print('PASS: bc keeps active/modified/live and pending terminals, preserves other windows, repeats safely and respects disabled winbar')
vim.cmd('qa!')
